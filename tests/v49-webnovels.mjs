import assert from 'node:assert/strict';
import {loadWebnovels,resetWebnovelsForTesting,listWebnovels,searchWebnovels,normalizeWebnovelIndex} from '../src/webnovels-v49.js';
import {catalogRoute} from '../src/catalog-v41.js';
const before=globalThis.fetch;
const books=Array.from({length:12500},(_,i)=>({id:100000+i,n:`A Chronicle of Star ${String(i).padStart(5,'0')}`,author:`Writer ${i%80}`}));
books.push({bookId:'12345678',bookName:'The Hidden Webnovel',authorName:'Author Example',coverUpdateTime:172000000});
assert.equal(normalizeWebnovelIndex({books}).length,12501);
assert.deepEqual(normalizeWebnovelIndex({books:normalizeWebnovelIndex({books})}).map(x=>x.key).slice(0,30),normalizeWebnovelIndex({books}).map(x=>x.key).slice(0,30));
let hits=0;
const env={ASSETS:{async fetch(){hits++;return new Response(JSON.stringify({books}),{headers:{'Content-Type':'application/json'}})}}};
resetWebnovelsForTesting();const local=await loadWebnovels(env);assert(local.rows.length>=12501);
assert.equal(hits,1);assert.equal((await loadWebnovels(env)).rows.length,local.rows.length);assert.equal(hits,1,'no unnecessary re-download');
const pageA=listWebnovels(local,{offset:0,limit:36});const pageB=listWebnovels(local,{offset:36,limit:36});
assert.equal(pageA.results.length,36);assert.equal(pageB.results.length,36);assert(pageA.hasMore);
assert.notEqual(pageA.results[0].title,pageB.results[0].title);
assert.equal(listWebnovels(local,{offset:12300,limit:60}).results.length,60);
assert.equal(searchWebnovels(local,'Hidden Webnovel')[0].title,'The Hidden Webnovel');
assert.equal(searchWebnovels(local,'Star 03570')[0].title,'A Chronicle of Star 03570');
assert.equal(searchWebnovels(local,'nonexistent random words').length,0);
const req=new Request('https://mediatok.org/api/webnovels/browse?offset=4100&limit=36');
const response=await catalogRoute(req,env,{});assert.equal(response.status,200);
const p=await response.json();assert.equal(p.results.length,36);assert(p.total>=12501);assert(p.hasMore);
const query=await catalogRoute(new Request('https://mediatok.org/api/webnovels/browse?q=Hidden%20Webnovel'),env,{});
assert.equal((await query.json()).total,1);
const search=await catalogRoute(new Request('https://mediatok.org/api/search/media?type=webnovel&q=Hidden%20Webnovel'),env,{});
assert((await search.json()).results.some(x=>x.title==='The Hidden Webnovel'));
assert.equal(hits,1);
resetWebnovelsForTesting();globalThis.fetch=async()=>{throw new Error('All provider connections down')};
const offline=await loadWebnovels({});assert(offline.rows.length>=90);
assert(searchWebnovels(offline,'Reverend Insanity').some(r=>r.title==='Reverend Insanity'));
globalThis.fetch=before;
console.log('PASS v49: 12,501 provider titles; 4k offset; directory filter; search; cache; offline fallback');
