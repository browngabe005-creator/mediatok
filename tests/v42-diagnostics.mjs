import assert from 'node:assert/strict';
import { catalogRoute } from '../src/catalog-v41.js';
let calls=[];
const realFetch=globalThis.fetch;
const reply=(body,status=200)=>new Response(JSON.stringify(body),{status,headers:{'content-type':'application/json'}});
globalThis.fetch=async (url,opts={})=>{
 const u=String(url);calls.push(u);
 if(u.includes('api.jikan.moe'))return reply({data:[{mal_id:1,title:'Naruto',images:{jpg:{large_image_url:'https://cdn.myanimelist.net/naruto.jpg'}}}]});
 if(u.includes('openlibrary.org'))return reply({docs:[]});
 if(u.includes('graphql.anilist.co'))return reply({data:{Page:{media:[]}}});
 if(u.includes('api.tvmaze.com'))return reply([]);
 if(u.includes('itunes.apple.com'))return reply({results:[]});
 if(u.includes('store.steampowered.com'))return reply({items:[]});
 if(u.includes('api.vndb.org'))return reply({results:[]});
 if(u.includes('googleapis.com'))return reply({items:[]});
 if(u.includes('kitsu.io'))return reply({data:[]});
 return reply({},404);
};
const ctx={waitUntil(p){p.catch(()=>{})}};
const env={DB:{prepare(s){return{bind(){return this},async first(){if(s.includes('COUNT(*)'))return {n:0};return null},async run(){return {success:true}}}}}};
const diagnosis=await catalogRoute(new Request('https://mediatok.org/api/search/v42/diagnostics?type=anime'),env,ctx);
const report=await diagnosis.json();assert.equal(diagnosis.status,200);assert.equal(report.version,'v43');assert.equal(report.providers[0].status,'ok');
const before=calls.length;
const r=await catalogRoute(new Request('https://mediatok.org/api/search/v42?type=all&q=naruto'),env,ctx);
const data=await r.json();assert.equal(r.status,200);assert.ok(data.results.some(x=>x.title==='Naruto'));
const launched=calls.length-before;assert.ok(launched<=6,`All-media issued too many upstream calls: ${launched}`);
const invalid=await catalogRoute(new Request('https://mediatok.org/api/search/v42/image?url=https://127.0.0.1'),env,ctx);
assert.equal(invalid.status,400);
console.log('PASS v42 diagnostics + bounded all-search + image host validation:', {upstreamCalls:launched});
globalThis.fetch=realFetch;
