import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,name TEXT,avc TEXT,role TEXT);
CREATE TABLE media_logs(id INTEGER PRIMARY KEY,user_id INTEGER,title TEXT,updated_at INTEGER);
CREATE TABLE log_comments(id INTEGER PRIMARY KEY,log_id INTEGER);
INSERT INTO users VALUES(1,'alice','','member'),(2,'bob','','member');`);
for(let i=1;i<=137;i++)db.prepare('INSERT INTO media_logs VALUES(?,?,?,?)').run(i,1,'Title '+i,i);
db.prepare('INSERT INTO media_logs VALUES(?,?,?,?)').run(138,2,'Other library',138);
const source=readFileSync(new URL('../src/worker.js',import.meta.url),'utf8');
const start=source.indexOf('  if (url.pathname === "/api/logs" && method === "GET")');
const end=source.indexOf('  if (url.pathname === "/api/logs" && method === "POST")',start);
const handler=new Function('db','url','method','json','logObject',`return (async()=>{${source.slice(start,end)}})()`);
const adapter={prepare(sql){const stmt=db.prepare(sql);return {bind(...args){return {all:async()=>({results:stmt.all(...args)})}},all:async()=>({results:stmt.all()})}}};
const query=path=>handler(adapter,new URL('https://mediatok.test'+path),'GET',x=>x,x=>x);
const rows=await query('/api/logs?user=ALICE');
assert.equal(rows.length,137);assert.equal(rows[0].title,'Title 137');assert.equal(rows.at(-1).title,'Title 1');assert(rows.every(x=>x.user_id===1));
assert.equal((await query('/api/logs')).length,40);
assert.equal((await query('/api/logs?user=missing')).length,0);
console.log('PASS: complete 137-title library, case-insensitive owner filter, ordering, empty user, bounded global feed');
